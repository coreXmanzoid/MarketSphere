"""
services/buyer_pdf.py

Dedicated ReportLab service for generating MarketSphere Buyer Profile reports.
"""
from io import BytesIO
from django.utils import timezone

from reportlab.lib import colors
from reportlab.lib.enums import TA_CENTER, TA_RIGHT, TA_LEFT
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import (
    SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, HRFlowable, KeepTogether
)

# =============================================================
# BRAND & STYLE CONSTANTS
# =============================================================
ACCENT_COLOR = colors.HexColor("#9D6638")
HEADING_COLOR = colors.HexColor("#4E220F")
MUTED_COLOR = colors.HexColor("#6B6B6B")
BORDER_COLOR = colors.HexColor("#D9D2C4")
LIGHT_BG = colors.HexColor("#F7F1DE")

PAGE_MARGIN = 20 * mm


def _get_styles():
    """Defines the typography system for the report."""
    styles = getSampleStyleSheet()

    styles.add(ParagraphStyle(
        name="ReportBrand",
        fontName="Helvetica-Bold",
        fontSize=20,
        textColor=HEADING_COLOR,
        spaceAfter=4,
    ))

    styles.add(ParagraphStyle(
        name="ReportTitle",
        fontName="Helvetica",
        fontSize=12,
        spaceBefore=4,
        textColor=MUTED_COLOR,
    ))

    styles.add(ParagraphStyle(
        name="MetaRight",
        fontName="Helvetica",
        fontSize=9,
        textColor=MUTED_COLOR,
        alignment=TA_RIGHT,
        leading=12,
    ))

    styles.add(ParagraphStyle(
        name="SectionHeading",
        fontName="Helvetica-Bold",
        fontSize=12,
        textColor=HEADING_COLOR,
        spaceBefore=15,
        spaceAfter=6,
    ))

    styles.add(ParagraphStyle(
        name="KeyStyle",
        fontName="Helvetica-Bold",
        fontSize=9,
        textColor=HEADING_COLOR,
    ))

    styles.add(ParagraphStyle(
        name="ValueStyle",
        fontName="Helvetica",
        fontSize=9,
        textColor=colors.black,
    ))
    
    styles.add(ParagraphStyle(
        name="NotesBody",
        fontName="Helvetica",
        fontSize=9,
        textColor=colors.black,
        leading=14,
    ))

    return styles


# =============================================================
# DATA EXTRACTION HELPERS (Graceful Fallbacks)
# =============================================================
def _get_attr(obj, attrs, default="—"):
    """Safely retrieves the first available attribute from a list."""
    for attr in attrs:
        if hasattr(obj, attr):
            val = getattr(obj, attr)
            if val not in [None, ""]:
                if hasattr(val, 'strftime'):
                    return val.strftime("%b %d, %Y %H:%M")
                return str(val)
    return default


def _get_related_manager(obj, names):
    """Safely retrieves a related manager by checking common naming patterns."""
    for name in names:
        if hasattr(obj, name):
            return getattr(obj, name)
    return None


def _format_currency(value):
    try:
        return f"Rs. {float(value or 0):,.2f}"
    except (TypeError, ValueError):
        return "Rs. 0.00"


# =============================================================
# DOCUMENT BUILDERS
# =============================================================
def _draw_footer(canvas, doc):
    """Canvas hook for drawing the universal footer on every page."""
    canvas.saveState()
    canvas.setFont("Helvetica", 8)
    canvas.setFillColor(MUTED_COLOR)
    
    timestamp = timezone.localtime().strftime("%Y-%m-%d %H:%M:%S")
    
    canvas.drawString(PAGE_MARGIN, 10 * mm, f"Generated by MarketSphere Admin Dashboard | {timestamp}")
    canvas.drawCentredString(A4[0] / 2.0, 10 * mm, "Confidential Document")
    canvas.drawRightString(A4[0] - PAGE_MARGIN, 10 * mm, f"Page {doc.page}")
    
    canvas.restoreState()


def _build_kv_table(data_list, styles):
    """Renders a structured 4-column Key-Value grid."""
    rows = []
    # Process items in chunks of 2 for a two-column (4 sub-columns) layout
    for i in range(0, len(data_list), 2):
        row = []
        # First Pair
        item1 = data_list[i]
        row.extend([Paragraph(item1[0], styles["KeyStyle"]), Paragraph(item1[1], styles["ValueStyle"])])
        
        # Second Pair (if exists)
        if i + 1 < len(data_list):
            item2 = data_list[i+1]
            row.extend([Paragraph(item2[0], styles["KeyStyle"]), Paragraph(item2[1], styles["ValueStyle"])])
        else:
            row.extend([Paragraph("", styles["KeyStyle"]), Paragraph("", styles["ValueStyle"])])
            
        rows.append(row)
        
    table = Table(rows, colWidths=[35*mm, 50*mm, 35*mm, 50*mm])
    table.setStyle(TableStyle([
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ('TOPPADDING', (0, 0), (-1, -1), 6),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 6),
        ('LINEBELOW', (0, 0), (-1, -1), 0.5, BORDER_COLOR),
    ]))
    return table


