def _draw_footer(canvas, doc):
    """Canvas hook for drawing the universal footer on every page matching buyer_pdf.py."""
    canvas.saveState()
    canvas.setFont("Helvetica", 8)
    canvas.setFillColor(MUTED_COLOR)
    
    timestamp = timezone.localtime().strftime("%Y-%m-%d %H:%M:%S")
    
    canvas.drawString(PAGE_MARGIN, 10 * mm, f"Generated by MarketSphere Admin Dashboard | {timestamp}")
    canvas.drawCentredString(A4[0] / 2.0, 10 * mm, "Confidential Document")
    canvas.drawRightString(A4[0] - PAGE_MARGIN, 10 * mm, f"Page {doc.page}")
    
    canvas.restoreState()


def _build_kv_table(data_list, styles):
    """Renders a structured 4-column Key-Value grid matching buyer_pdf.py."""
    rows = []
    for i in range(0, len(data_list), 2):
        row = []
        item1 = data_list[i]
        row.extend([Paragraph(item1[0], styles["KeyStyle"]), Paragraph(str(item1[1]), styles["ValueStyle"])])
        
        if i + 1 < len(data_list):
            item2 = data_list[i+1]
            row.extend([Paragraph(item2[0], styles["KeyStyle"]), Paragraph(str(item2[1]), styles["ValueStyle"])])
        else:
            row.extend([Paragraph("", styles["KeyStyle"]), Paragraph("", styles["ValueStyle"])])
            
        rows.append(row)
        
    table = Table(rows, colWidths=[35*mm, 50*mm, 35*mm, 50*mm])
    table.setStyle(TableStyle([
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ('TOPPADDING', (0, 0), (-1, -1), 6),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 6),
        ('LINEBELOW', (0, 0), (-1, -1), 0.5, BORDER_COLOR),
    ]))
    return table


def _build_data_table(headers, row_data, col_widths, styles, align_left_cols=None, align_right_cols=None):
    """Builds a formatted list table with alternating row colors matching the theme."""
    align_left_cols = align_left_cols or []
    align_right_cols = align_right_cols or []
        
    table_data = []
    
    header_row = []
    for header in headers:
        header_row.append(Paragraph(header, styles["TableHeader"]))
    table_data.append(header_row)
    
    if not row_data:
        empty_row = [Paragraph("<i>No data available</i>", styles["TableCellLeft"])] + [""] * (len(headers) - 1)
        table_data.append(empty_row)
    else:
        for row in row_data:
            formatted_row = []
            for idx, cell_value in enumerate(row):
                if idx in align_left_cols:
                    style = styles["TableCellLeft"]
                elif idx in align_right_cols:
                    style = styles["TableCellRight"]
                else:
                    style = styles["TableCell"]
                formatted_row.append(Paragraph(str(cell_value), style))
            table_data.append(formatted_row)
            
    t = Table(table_data, colWidths=col_widths, repeatRows=1)
    
    t_style = [
        ('BACKGROUND', (0, 0), (-1, 0), HEADING_COLOR),
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ('TOPPADDING', (0, 0), (-1, -1), 6),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 6),
        ('BOX', (0, 0), (-1, -1), 0.5, BORDER_COLOR),
        ('INNERGRID', (0, 0), (-1, -1), 0.25, BORDER_COLOR),
    ]
    
    if row_data:
        t_style.append(('ROWBACKGROUNDS', (0, 1), (-1, -1), [colors.white, LIGHT_BG]))
        
    t.setStyle(TableStyle(t_style))
    return t


